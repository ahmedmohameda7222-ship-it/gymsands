export const nutritionV1Dictionaries: Record<"en" | "de" | "ar", NutritionV1Dictionary> = { en, de, ar };

export function useNutritionV1Translation() {
  const { language, dir } = useTranslation();
  const locale = language === "de" ? "de-DE" : language === "ar" ? "ar-EG" : "en-GB";
  const nt = useCallback((key: NutritionV1Key, values?: Record<string, string | number>) => {
    const template = nutritionV1Dictionaries[language][key];
    if (!values) return template;
    return Object.entries(values).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), template);
  }, [language]);
  return { nt, language, dir, locale };
}
