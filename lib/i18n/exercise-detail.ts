const dictionaries = { en, de, ar } as const;
export function useExerciseDetailTranslation() {
  const { language, dir } = useTranslation();
  const locale =
    language === "de" ? "de-DE" : language === "ar" ? "ar-EG" : "en-GB";
  const ed = useCallback(
    (key: Key, values?: Record<string, string | number>) => {
      const template = dictionaries[language][key];
      return values
        ? Object.entries(values).reduce(
            (value, [name, replacement]) =>
              value.replaceAll(`{${name}}`, String(replacement)),
            template,
          )
        : template;
    },
    [language],
  );
  return { language, dir, locale, ed };
}
